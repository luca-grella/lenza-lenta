// Regenerates sw-assets.js: the ONE list of files the service worker precaches.
// Run after adding/removing app files:  node tools/sw-assets.mjs
// Includes index.html, manifest, css/, src/ (minus src/ui/dev), vendor/ (js only), icons/ (png/svg).
// Excludes sandboxes, docs, tools, tmp. Then bump CACHE in sw.js.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = [];
function walk(dir, filter) {
  let names; try { names = readdirSync(join(root, dir)); } catch { return; }
  for (const n of names.sort()) {
    if (n.startsWith('.')) continue;
    const rel = dir ? `${dir}/${n}` : n;
    if (statSync(join(root, rel)).isDirectory()) walk(rel, filter);
    else if (filter(rel)) out.push(rel);
  }
}
out.push('./', 'index.html', 'manifest.webmanifest');
walk('css', f => f.endsWith('.css'));
walk('src', f => f.endsWith('.js') && !f.startsWith('src/ui/dev/'));
walk('vendor', f => f.endsWith('.js') && !f.endsWith('/RenderPass.js'));  // RenderPass is never imported
walk('icons', f => /\.(png|svg)$/.test(f));
const body = `// GENERATED by tools/sw-assets.mjs — do not edit by hand.\nself.SW_ASSETS = ${JSON.stringify(out, null, 1)};\n`;
writeFileSync(join(root, 'sw-assets.js'), body);
console.log(`sw-assets.js: ${out.length} files`);
